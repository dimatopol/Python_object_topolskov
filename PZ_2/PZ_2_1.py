#С начала суток прошло секунд (N - целое). Найти количество полных минут, прошедших с начала суток.
n = input("Введите целое число (секунд): ")
while type(n) != int:
    try:
        n = int(n)
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите целое число (секунд): ")

minutes = n // 60
print("Количество полных минут, прошедших с начала суток: ", minutes)
